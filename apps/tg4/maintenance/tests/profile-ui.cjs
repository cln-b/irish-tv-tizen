const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),app=path.join(root,'../tv-app');
const index=fs.readFileSync(path.join(app,'index.html'),'utf8');
const cssFiles=fs.readdirSync(path.join(app,'css'));
assert.ok(cssFiles.length>=15,'All upstream CSS chunks must be generated');
for(const file of cssFiles)assert.ok(index.includes('href="css/'+file+'"'),'Missing CSS link for '+file);
assert.ok(index.includes('href="profile-ui.css"'),'Profile/Login UI fix must be linked');
const ui=fs.readFileSync(path.join(app,'profile-ui.css'),'utf8');
const flat=ui.replace(/\s+/g,' ');
assert.match(ui,/\.cpa_qr_code\[data-v-21e9c5e0\]/, 'Login QR override must be scoped');
assert.match(ui,/\.user-details-qr-code\[data-v-a8e0e570\]/, 'Details QR override must be scoped');
assert.match(ui,/display:block !important/,'Inline display:inline must be overridden');
assert.match(ui,/url\("img\/profile-qr\.png"\) !important/,'Details QR must use the bundled PNG');
assert.match(flat,/\.cpa_qr_code\[data-v-21e9c5e0\]\s*\{[^}]*width:447px\s*!important;[^}]*margin-bottom:53px/,'Login QR must use the corrected 447px/53px geometry');
assert.match(flat,/\.user-details-mid-section\[data-v-a8e0e570\]\s*\{[^}]*display:-webkit-flex\s*!important;[^}]*margin-top:40px\s*!important/,'Details mid-section must use legacy -webkit-flex and 40px top margin');
assert.match(flat,/\.list-grid\[data-v-059afbbf\]\s*\{[^}]*padding:0 0 80px 25px/,'Bookmarks/History list padding must be restored');
assert.match(flat,/\.main_area\[data-v-85c96466\][^}]*display:-webkit-flex\s*!important/,'App shell must use legacy -webkit-flex, not bare flex');
assert.match(flat,/\.top_bar\[data-v-85c96466\][^}]*display:-webkit-flex\s*!important/,'Top bar must use legacy -webkit-flex');
assert.match(flat,/\.profile-list\[data-v-059afbbf\][^}]*display:-webkit-flex\s*!important/,'Bookmarks/History profile list must use legacy -webkit-flex');
assert.match(flat,/\.cms-item-container\[data-v-8c064512\][^}]*display:-webkit-flex\s*!important/,'Bookmarks/History rows must use legacy -webkit-flex');
assert.match(flat,/-webkit-flex-direction:(column|row) !important/,'Prefixed flex direction must be set');
assert.match(flat,/-webkit-align-items:(center|flex-start) !important/,'Prefixed alignment must be set');
assert.match(flat,/-webkit-flex:1 1 auto !important/,'Prefixed grow/shrink must be set');
const declarations=ui.replace(/\/\*[\s\S]*?\*\//g,'');
assert.ok(!/display:\s*flex/.test(declarations),'No bare display:flex may remain in the WebKit 538.1 override');
const png=fs.readFileSync(path.join(app,'img/profile-qr.png'));
assert.equal(png.slice(1,4).toString(),'PNG','Bundled profile QR must be a PNG');
console.log('PASS profile CSS preload, legacy flex, QR geometry and bundled Details QR');
